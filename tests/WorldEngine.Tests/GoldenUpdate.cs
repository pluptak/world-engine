using System.IO.Compression;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace WorldEngine.Tests;

// Regenerating a golden from .NET itself. With WORLD_ENGINE_UPDATE_GOLDENS=1 a golden test that supports it writes what the engine does
// into the fixture in the source tree (Fixtures/, not the copy in bin/) and passes, instead of comparing. The change to the fixture is
// then a diff to read: a golden moves only on purpose, in the same commit as the behaviour that moved it.
//
//   WORLD_ENGINE_UPDATE_GOLDENS=1 dotnet test --filter "FullyQualifiedName~VerbMatrixTests"
//
// The goldens that support it: the verb matrix, the verb catalog, the property trace, the tamper, takeover and template-fuzz sets, the scripted rows
// (memory worlds, refine, beat shapes), the projection, handle, actor-view and engine-query rows, the CLI player and actor ops,
// the options rows, the carry rows, the CLI meta ops (only the rows that moved), and GoldenRows' command and validate rows. The rest are bespoke and are edited by hand, or
// regenerated by their script in tools/golden-gen while TypeScript is still in the tree (tools/golden-gen/README.md).
internal static class GoldenUpdate
{
    public static bool Enabled => Environment.GetEnvironmentVariable("WORLD_ENGINE_UPDATE_GOLDENS") == "1";

    // The fixture in the source tree: found by walking up from the test's folder to the one that holds tests/WorldEngine.Tests.
    public static string SourcePath(string fixture)
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            var candidate = Path.Combine(dir.FullName, "tests", "WorldEngine.Tests", "Fixtures");
            if (Directory.Exists(candidate))
            {
                return Path.Combine(candidate, fixture);
            }
        }
        throw new DirectoryNotFoundException("The source tree's Fixtures folder is not above the test run");
    }

    // Writes a fixture in the layout it already has: indented as the file is, one line when it is.
    public static void Write(string fixture, JsonNode value)
    {
        var path = SourcePath(fixture);
        var existing = File.Exists(path) ? File.ReadAllText(path) : "";
        var indented = IsIndented(existing);
        var text = value.ToJsonString(new JsonSerializerOptions
        {
            WriteIndented = indented,
            IndentSize = indented ? IndentOf(existing) : 2,
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        });
        File.WriteAllText(path, text + "\n");
    }

    // The same for a gzipped fixture, which is always one line.
    public static void WriteGzip(string fixture, JsonNode value)
    {
        using var file = File.Create(SourcePath(fixture));
        using var zip = new GZipStream(file, CompressionLevel.SmallestSize);
        zip.Write(Encoding.UTF8.GetBytes(value.ToJsonString(new JsonSerializerOptions { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping })));
    }

    // The width of the file's first indent, so a rewrite keeps its layout.
    private static int IndentOf(string text)
    {
        var secondLine = text.Split('\n').Skip(1).FirstOrDefault() ?? "";
        var width = secondLine.Length - secondLine.TrimStart(' ').Length;
        return width > 0 ? width : 2;
    }

    private static bool IsIndented(string text)
    {
        var firstBreak = text.IndexOf('\n');
        return firstBreak >= 0 && firstBreak < text.Length - 1;
    }
}
